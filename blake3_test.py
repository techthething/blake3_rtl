def make_input(n: int) -> bytes:
    return bytes(i % 251 for i in range(n))


@pytest.mark.parametrize("n", sorted(VECTORS))
def test_hash_extended_output(n):
    assert Blake3().hash(make_input(n), 131).hex() == VECTORS[n][0]


@pytest.mark.parametrize("n", sorted(VECTORS))
def test_default_digest_is_prefix(n):
    assert Blake3().hash(make_input(n)).hex() == VECTORS[n][0][:64]


@pytest.mark.parametrize("n", sorted(VECTORS))
def test_keyed_hash_extended_output(n):
    assert Blake3(bytes_to_words32(KEY), KEYED_HASH).hash(make_input(n), 131).hex() == VECTORS[n][1]


def test_empty_input_known_digest():
    assert Blake3().hash(b"").hex() == (
        "af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262"
    )


@pytest.mark.parametrize("n", [0, 64, 65, 200, 1024, 1025, 5000])
def test_xof_prefix_property(n):
    data = make_input(n)
    long = Blake3().hash(data, 300)
    for out_len in (1, 32, 64, 65, 128):
        assert Blake3().hash(data, out_len) == long[:out_len]


def test_instance_is_reusable():
    b3 = Blake3()
    data = make_input(5000)
    first = b3.hash(data)
    b3.hash(make_input(3000))          # unrelated call in between
    assert b3.hash(data) == first      # no state leaks between calls